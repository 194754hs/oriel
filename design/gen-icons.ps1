# Converts the chosen icon set into a generated C++ table of SVG path data.
# Pure ASCII.
#
# The set stays the source of truth: change $set and the map below and rerun.
# Non-path elements (circle, rect, line) are reduced to path data here so the
# runtime only ever has to understand one thing.
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$set  = Join-Path $PSScriptRoot 'icon-sets\lucide\package'
$dir  = Join-Path $set 'icons'
$ver  = (Get-Content (Join-Path $set 'package.json') -Raw | ConvertFrom-Json).version

