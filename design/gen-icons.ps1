 ,@{e='Pdf';           n='file-type'}
 ,@{e='Image';         n='file-image'}
 ,@{e='Video';         n='file-video'}
 ,@{e='Archive';       n='file-archive'}
 ,@{e='Audio';         n='file-music'}
 ,@{e='Code';          n='file-code'}
 ,@{e='App';           n='app-window'}
 ,@{e='Clock';         n='clock'}
 ,@{e='Desktop';       n='monitor'}
 ,@{e='Download';      n='download'}
 ,@{e='Star';          n='star'}
 ,@{e='Pc';            n='computer'}
 ,@{e='Drive';         n='hard-drive'}
 ,@{e='Cloud';         n='cloud'}
 ,@{e='Network';       n='network'}
 ,@{e='ChevronRight';  n='chevron-right'}
 ,@{e='ChevronLeft';   n='chevron-left'}
 ,@{e='ChevronDown';   n='chevron-down'}
